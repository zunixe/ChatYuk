-- ---------- 1) room_members.broadcast_granted ----------
-- Flag "boleh broadcast" persisten per anggota, dibaca klien lewat
-- list_room_members_v2 (border avatar broadcaster) dan
-- private_room_service.dart (myBroadcastGranted).
alter table public.room_members
  add column if not exists broadcast_granted boolean not null default false;

comment on column public.room_members.broadcast_granted is
  'Izin broadcast persisten per anggota room (dibaca list_room_members_v2).';

-- ---------- 2) app_settings.app_shared_secret ----------
-- Secret service-to-service: edge function memverifikasi header
-- x-app-secret terhadap nilai ini. Nilai SENGAJA tidak diberi default
-- di repo (rahasia). Isi manual:
--   update public.app_settings set app_shared_secret = '<secret>'
--    where id = 'global';
alter table public.app_settings
  add column if not exists app_shared_secret text;

comment on column public.app_settings.app_shared_secret is
  'Secret untuk header x-app-secret antar edge function. Isi manual per environment.';

-- ---------- 3) debug_notify_log ----------
-- Telemetri debug pengiriman notifikasi. Hanya untuk diagnosa.
create table if not exists public.debug_notify_log (
  id         integer generated by default as identity primary key,
  msg        text,
  created_at timestamptz not null default now()
);

alter table public.debug_notify_log enable row level security;

